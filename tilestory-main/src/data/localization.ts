export function t(key: keyof typeof TRANSLATIONS.en, lang: 'en' | 'tr' = 'en', params?: Record<string, string | number>): string {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let text = dictionary[key] || TRANSLATIONS.en[key] || (key as string);
  if (params) {
    Object.entries(params).forEach(([k, val]) => {
      text = text.replace(`{${k}}`, String(val));
    });
  }
  return text;
}
